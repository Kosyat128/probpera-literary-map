function git(root, args, options = {}) {
  return execFileSync("git", args, {
    cwd: root,
    encoding: options.encoding ?? "utf8",
    maxBuffer: 128 * 1024 * 1024,
    windowsHide: true,
  });
}

function gitText(root, sha, relativePath) {
  return git(root, ["show", `${sha}:${relativePath}`]);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function lineNumberAt(source, offset) {
  let line = 1;
  for (let index = 0; index < offset; index += 1) {
    if (source.charCodeAt(index) === 10) line += 1;
  }
  return line;
}

function findOpeningBrace(source, start, end) {
  let quote = "";
  let comment = false;
  for (let index = start; index < end; index += 1) {
    const char = source[index];
    const next = source[index + 1];
    if (comment) {
      if (char === "*" && next === "/") {
        comment = false;
        index += 1;
      }
      continue;
    }
    if (!quote && char === "/" && next === "*") {
      comment = true;
      index += 1;
      continue;
    }
    if (quote) {
      if (char === "\\") index += 1;
      else if (char === quote) quote = "";
      continue;
    }
    if (char === '"' || char === "'") {
      quote = char;
      continue;
    }
    if (char === "{") return index;
  }
  return -1;
}

function findClosingBrace(source, opening, end) {
  let depth = 1;
  let quote = "";
  let comment = false;
  for (let index = opening + 1; index < end; index += 1) {
    const char = source[index];
    const next = source[index + 1];
    if (comment) {
      if (char === "*" && next === "/") {
        comment = false;
        index += 1;
      }
      continue;
    }
    if (!quote && char === "/" && next === "*") {
      comment = true;
      index += 1;
      continue;
    }
    if (quote) {
      if (char === "\\") index += 1;
      else if (char === quote) quote = "";
      continue;
    }
    if (char === '"' || char === "'") {
      quote = char;
      continue;
    }
    if (char === "{") depth += 1;
    if (char === "}") depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error(`Unclosed CSS block starting at offset ${opening}`);
}

function trimRuleHeader(header) {
  const withoutComments = header.replace(/\/\*[\s\S]*?\*\//gu, " ").trim();
  const lastSemicolon = withoutComments.lastIndexOf(";");
  return (lastSemicolon >= 0
    ? withoutComments.slice(lastSemicolon + 1)
    : withoutComments
  ).trim();
}

export function splitSelectors(header) {
  const selectors = [];
  let start = 0;
  let round = 0;
  let square = 0;
  let quote = "";
  for (let index = 0; index < header.length; index += 1) {
    const char = header[index];
    if (quote) {
      if (char === "\\") index += 1;
      else if (char === quote) quote = "";
      continue;
    }
    if (char === '"' || char === "'") quote = char;
    else if (char === "(") round += 1;
    else if (char === ")") round -= 1;
    else if (char === "[") square += 1;
    else if (char === "]") square -= 1;
    else if (char === "," && round === 0 && square === 0) {
      selectors.push(header.slice(start, index).trim());
      start = index + 1;
    }
  }
  selectors.push(header.slice(start).trim());
  return selectors.filter(Boolean);
}

function parseDeclarations(body) {
  const declarations = [];
  const declarationPattern = /(?:^|;)\s*(--[\w-]+|[a-zA-Z-]+)\s*:\s*([^;{}]+)/gu;
  for (const match of body.matchAll(declarationPattern)) {
    declarations.push({
      property: match[1].trim(),
      value: match[2].replace(/\s+/gu, " ").trim(),
    });
  }
  return declarations;
}

export function parseCss(source, file = "<inline>") {
  const rules = [];

  function parseRange(start, end, contexts) {
    let cursor = start;
    while (cursor < end) {
      const opening = findOpeningBrace(source, cursor, end);
      if (opening < 0) break;
      const closing = findClosingBrace(source, opening, end);
      const header = trimRuleHeader(source.slice(cursor, opening));
      if (!header) {
        cursor = closing + 1;
        continue;
      }
      const bodyStart = opening + 1;
      if (/^@(media|supports|container|layer|document)\b/iu.test(header)) {
        parseRange(bodyStart, closing, [...contexts, header]);
      } else if (!/^@(?:keyframes|-webkit-keyframes)\b/iu.test(header)) {
        const declarations = parseDeclarations(source.slice(bodyStart, closing));
        if (declarations.length) {
          for (const selector of splitSelectors(header)) {
            rules.push({
              selector,
              declarations,
              contexts,
              file,
              line: lineNumberAt(source, opening - header.length),
            });
          }
        }
      }
      cursor = closing + 1;
    }
  }

  parseRange(0, source.length, []);
  return rules;
}

export function selectorMatches(candidate, registered, mode = "exact") {
  if (candidate === registered) return true;
  if (mode === "exact") return false;
  if (!candidate.startsWith(registered)) return false;
  const boundary = candidate[registered.length];
  if (mode === "state") return [":", ".", "["].includes(boundary);
  return [":", ".", "[", " ", ">", "+", "~"].includes(boundary);
}

function mediaScope(contexts) {
  const media = contexts.filter((item) => item.startsWith("@media"));
  return media.length ? media.join(" + ") : "all viewports";
}

function localeScope(selector, contexts) {
  const scope = `${selector} ${contexts.join(" ")}`;
  const hasEnglish = /(?:lang|language)[^\w]*(?:=|\()[^\w]*en\b/iu.test(scope);
  const hasRussian = /(?:lang|language)[^\w]*(?:=|\()[^\w]*ru\b/iu.test(scope);
  if (hasEnglish && hasRussian) return "RU+EN";
  if (hasEnglish) return "EN";
  if (hasRussian) return "RU";
  return "RU+EN";
}

function propertyBelongsTo(category, declaration) {
  const property = declaration.property;
  const value = declaration.value;
  if (category === "typography") {
    return /^(?:font(?:-.+)?|line-height|letter-spacing|text-(?:align|transform|decoration|indent|wrap)|white-space)$/u.test(
      property
    );
  }
  if (category === "spacing") {
    return /^(?:margin|padding|gap|row-gap|column-gap|inset|top|right|bottom|left|min-(?:width|height)|max-(?:width|height)|width|height|grid-template-(?:columns|rows)|align-items|justify-content)(?:-.+)?$/u.test(
      property
    ) || /^(?:--ui-(?:space|control|radius)|--sticky-navigation-offset)/u.test(property);
  }
  if (category === "colors") {
    return /^(?:color|background(?:-color)?|border(?:-.+)?-color|outline-color|box-shadow|text-shadow|fill|stroke)$/u.test(
      property
    ) || (property.startsWith("--") && /(?:#|rgb|hsl|oklch|color|orange|violet|cream|ink|muted|line)/iu.test(value));
  }
  if (category === "backgrounds") {
    return /^(?:background(?:-.+)?|box-shadow|filter|backdrop-filter|opacity|isolation|z-index|position|inset|top|right|bottom|left)$/u.test(
      property
    ) || /^(?:--cms-.+(?:surface|tint)|--reader-(?:bg|paper))$/u.test(property);
  }
  if (category === "motion") {
    return /^(?:animation(?:-.+)?|transition(?:-.+)?|transform(?:-.+)?|transform-origin|will-change|scroll-behavior)$/u.test(
      property
    );
  }
  if (category === "buttons") {
    return /^(?:display|place-items|align-items|justify-content|gap|width|min-width|max-width|height|min-height|max-height|padding(?:-.+)?|margin(?:-.+)?|font(?:-.+)?|line-height|letter-spacing|text-.+|color|background(?:-.+)?|border(?:-.+)?|border-radius|outline(?:-.+)?|box-shadow|opacity|cursor|transition(?:-.+)?|transform|visibility)$/u.test(
      property
    );
  }
  if (category === "card-families") {
    return !/^(?:content|pointer-events)$/u.test(property);
  }
  return false;
}

function inventoryFromRules(category, definition, rules) {
  return definition.entries.map((registered) => {
    if (!VALID_DECISIONS.has(registered.decision)) {
      throw new Error(
        `Invalid decision ${registered.decision} for ${category}:${registered.selector}`
      );
    }
    const matches = rules
      .filter((rule) =>
        selectorMatches(rule.selector, registered.selector, registered.match)
      )
      .map((rule) => ({
        selector: rule.selector,
        file: rule.file,
        line: rule.line,
        viewport: mediaScope(rule.contexts),
        locale: localeScope(rule.selector, rule.contexts),
        declarations: rule.declarations.filter((declaration) =>
          propertyBelongsTo(category, declaration)
        ),
      }))
      .filter((rule) => rule.declarations.length > 0);

    if (!matches.length) {
      throw new Error(
        `Inventory selector has no matching ${category} declarations: ${registered.selector}`
      );
    }
    const runtimeObservations = runtimeObservedFindings.filter(
      (finding) => finding.selector === registered.selector
    );
    return {
      selector: registered.selector,
      match: registered.match,
      decision: registered.decision,
      reason: registered.reason,
      computed: runtimeObservations.length
        ? {
            status: "MEASURED",
            evidence: runtimeObservations.map((finding) => finding.id),
          }
        : {
            status: NOT_MEASURED,
            reason: COMPUTED_REASON,
          },
      runtimeObservations,
      declaredRules: matches,
    };
  });
}

function gitTree(root, sha) {
  const output = git(root, ["ls-tree", "-r", "-l", sha]);
  return output
    .split(/\r?\n/u)
    .filter(Boolean)
    .map((line) => {
      const match = line.match(/^\d+\s+blob\s+([0-9a-f]+)\s+(\d+|-)\t(.+)$/u);
      if (!match) throw new Error(`Unexpected git ls-tree row: ${line}`);
      return {
        object: match[1],
        bytes: match[2] === "-" ? null : Number(match[2]),
        path: match[3].replaceAll("\\", "/"),
      };
    });
}

function sumBytes(files) {
  return files.reduce((sum, file) => sum + (file.bytes ?? 0), 0);
}

function measuredFileSet(files) {
  return { status: "MEASURED", files: files.length, bytes: sumBytes(files) };
}

function localDistTree(root) {
  const distRoot = path.join(root, "dist");
  if (!existsSync(distRoot)) return [];
  const files = [];

  function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true }).toSorted(
      (first, second) => first.name.localeCompare(second.name, "en")
    )) {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) visit(absolute);
      else if (entry.isFile()) {
        files.push({
          absolute,
          bytes: statSync(absolute).size,
          path: path.relative(root, absolute).replaceAll("\\", "/"),
        });
      }
    }
  }

  visit(distRoot);
  return files.toSorted((first, second) =>
    first.path.localeCompare(second.path, "en")
  );
}

function distManifestSha256(files) {
  const hash = createHash("sha256");
  for (const file of files) {
    hash.update(file.path);
    hash.update("\0");
    hash.update(String(file.bytes));
    hash.update("\0");
    hash.update(readFileSync(file.absolute));
    hash.update("\0");
  }
  return hash.digest("hex");
}

function notMeasured(reason) {
  return { status: NOT_MEASURED, reason };
}

function budgetMetric(actual, limit) {
  if (actual === null) {
    return {
      actual: NOT_MEASURED,
      limit,
      headroom: NOT_MEASURED,
      result: NOT_MEASURED,
    };
  }
  return {
    actual,
    limit,
    headroom: limit - actual,
    result: actual <= limit ? "PASS" : "FAIL",
  };
}

function assertEvidence(condition, message) {
  if (!condition) {
    throw new Error(`Invalid verified production evidence: ${message}`);
  }
}

function readVerifiedProductionEvidence(root, budget) {
  const relativePath = stage5BaselineProvenance.verifiedProductionEvidencePath;
  const absolutePath = path.join(root, relativePath);
  assertEvidence(existsSync(absolutePath), `${relativePath} is missing`);

  const evidence = JSON.parse(readFileSync(absolutePath, "utf8"));
  const expected = stage5BaselineProvenance.verifiedProduction;
  const identity = evidence.baselineIdentity;
  const artifact = evidence.productionArtifact;
  const source = artifact?.source;
  const performance = artifact?.performance;

  assertEvidence(evidence.schemaVersion === 1, "schemaVersion must be 1");
  assertEvidence(
    identity?.baseMainSha === stage5BaselineProvenance.baseMainSha,
    "baselineIdentity.baseMainSha is not BASE_MAIN_SHA"
  );
  assertEvidence(
    identity?.integrationStartSha === stage5BaselineProvenance.integrationStartSha,
    "baselineIdentity.integrationStartSha drifted"
  );
  assertEvidence(
    identity?.sourceTreeSha === stage5BaselineProvenance.sourceTreeSha,
    "baselineIdentity.sourceTreeSha drifted"
  );
  assertEvidence(
    JSON.stringify(identity?.repositoryManifest) ===
      JSON.stringify(stage5BaselineProvenance.repositoryManifest),
    "baselineIdentity.repositoryManifest drifted"
  );
  assertEvidence(artifact?.status === "PASS", "productionArtifact.status must be PASS");
  assertEvidence(
    artifact?.classification === PRODUCTION_EVIDENCE_CLASSIFICATION &&
      artifact.classification === expected.classification,
    "production artifact classification is not exact Pages evidence"
  );
  assertEvidence(
    source?.runId === expected.workflowRunId,
    `workflow run must be ${expected.workflowRunId}`
  );
  assertEvidence(
    source?.artifactId === expected.artifactId,
    `artifact id must be ${expected.artifactId}`
  );
  assertEvidence(
    source?.releaseHead?.commitSha === expected.releaseSha &&
      expected.releaseSha === stage5BaselineProvenance.baseMainSha,
    "release-head SHA is not bound to BASE_MAIN_SHA"
  );
  assertEvidence(
    performance?.artifact?.status === "MEASURED",
    "production artifact measurement is missing"
  );
  assertEvidence(
    performance.artifact.files === expected.files,
    `production artifact must contain ${expected.files} files`
  );
  assertEvidence(
    performance.artifact.bytes === expected.bytes,
    `production artifact must contain ${expected.bytes} bytes`
  );
  assertEvidence(
    performance.artifact.manifestSha256 === expected.manifestSha256,
    "production artifact manifest SHA-256 drifted"
  );

  const pinnedBudgetSource = gitText(
    root,
    stage5BaselineProvenance.baseMainSha,
    "performance-budget.json"
  );
  assertEvidence(
    artifact.measurement?.budgetSource?.sha256 === sha256(pinnedBudgetSource),
    "budget source is not bound to performance-budget.json at BASE_MAIN_SHA"
  );
  for (const [name, limit] of Object.entries(budget)) {
    const metric = performance.metrics?.[name];
    assertEvidence(metric, `production metric ${name} is missing`);
    assertEvidence(metric.limit === limit, `${name} limit is not the pinned budget`);
    assertEvidence(metric.actual <= limit, `${name} exceeds its pinned budget`);
    assertEvidence(metric.result === "PASS", `${name} result must be PASS`);
  }

  return evidence;
}

