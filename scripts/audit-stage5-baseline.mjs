function productionDistPerformance(root, dist, budget) {
  if (!dist.length) {
    const unavailable = notMeasured(
      "No local production dist is available. Run the production build before writing the baseline."
    );
    const metrics = Object.fromEntries(
      Object.entries(budget).map(([name, limit]) => [name, budgetMetric(null, limit)])
    );
    return {
      artifact: unavailable,
      metrics,
      css: unavailable,
      globeChunks: unavailable,
      initialRequests: notMeasured("Requires a browser/network trace of the exact production build."),
    };
  }

  const relative = (file) => file.path.slice("dist/".length);
  const scripts = dist.filter((file) => file.path.endsWith(".js"));
  const css = dist.filter((file) => file.path.endsWith(".css"));
  const assets = dist.filter((file) => relative(file).startsWith("assets/"));
  const covers = dist.filter((file) => relative(file).startsWith("brand/book-covers/"));
  const images = dist.filter((file) => /\.(?:avif|jpe?g|png|webp)$/iu.test(file.path));
  const portraits = images.filter((file) =>
    relative(file).startsWith("assets/writer-portraits/")
  );
  const main = scripts
    .filter((file) => /^assets\/index-/u.test(relative(file)))
    .toSorted((a, b) => b.bytes - a.bytes)[0];
  const largest = scripts.toSorted((a, b) => b.bytes - a.bytes)[0];
  const globeTexture = dist.find((file) =>
    relative(file).endsWith("textures/antique-world-1887.webp")
  );
  const otherImages = images.filter((file) => file !== globeTexture);
  const globeChunks = scripts.filter((file) =>
    /(?:globe|worldmap|three-vendor)/iu.test(relative(file))
  );
  const gzipBytes = (file) =>
    file
      ? gzipSync(readFileSync(file.absolute), {
          level: 9,
        }).byteLength
      : null;
  const coverBytes = sumBytes(covers);
  const portraitBytes = sumBytes(portraits);
  const metrics = {
    distTotalBytes: budgetMetric(sumBytes(dist), budget.distTotalBytes),
    distExcludingBookCoversBytes: budgetMetric(
      sumBytes(dist) - coverBytes,
      budget.distExcludingBookCoversBytes
    ),
    largestJavaScriptBytes: budgetMetric(
      largest?.bytes ?? 0,
      budget.largestJavaScriptBytes
    ),
    largestJavaScriptGzipBytes: budgetMetric(
      gzipBytes(largest) ?? 0,
      budget.largestJavaScriptGzipBytes
    ),
    mainJavaScriptBytes: budgetMetric(main?.bytes ?? 0, budget.mainJavaScriptBytes),
    mainJavaScriptGzipBytes: budgetMetric(
      gzipBytes(main) ?? 0,
      budget.mainJavaScriptGzipBytes
    ),
    globeTextureBytes: budgetMetric(
      globeTexture?.bytes ?? 0,
      budget.globeTextureBytes
    ),
    writerPortraitTotalBytes: budgetMetric(
      portraitBytes,
      budget.writerPortraitTotalBytes
    ),
    writerPortraitAverageBytes: budgetMetric(
      portraits.length ? Math.ceil(portraitBytes / portraits.length) : 0,
      budget.writerPortraitAverageBytes
    ),
    writerPortraitMaximumBytes: budgetMetric(
      portraits.reduce((maximum, file) => Math.max(maximum, file.bytes ?? 0), 0),
      budget.writerPortraitMaximumBytes
    ),
    bookCoverCount: budgetMetric(covers.length, budget.bookCoverCount),
    bookCoverTotalBytes: budgetMetric(coverBytes, budget.bookCoverTotalBytes),
    bookCoverAverageBytes: budgetMetric(
      covers.length ? Math.ceil(coverBytes / covers.length) : 0,
      budget.bookCoverAverageBytes
    ),
    bookCoverMaximumBytes: budgetMetric(
      covers.reduce((maximum, file) => Math.max(maximum, file.bytes ?? 0), 0),
      budget.bookCoverMaximumBytes
    ),
    individualImageBytes: budgetMetric(
      otherImages.reduce((maximum, file) => Math.max(maximum, file.bytes ?? 0), 0),
      budget.individualImageBytes
    ),
  };
  const largestCss = css.toSorted((a, b) => b.bytes - a.bytes)[0];
  return {
    artifact: {
      ...measuredFileSet(dist),
      source: "local production dist/",
      manifestSha256: distManifestSha256(dist),
    },
    metrics,
    assets: measuredFileSet(assets),
    css: {
      ...measuredFileSet(css),
      gzipBytes: css.reduce((sum, file) => sum + gzipBytes(file), 0),
      largest: largestCss
        ? {
            path: relative(largestCss),
            bytes: largestCss.bytes,
            gzipBytes: gzipBytes(largestCss),
          }
        : null,
    },
    globeChunks: {
      ...measuredFileSet(globeChunks),
      entries: globeChunks.map((file) => ({
        path: relative(file),
        bytes: file.bytes,
        gzipBytes: gzipBytes(file),
      })),
    },
    largestJavaScript: largest
      ? {
          path: relative(largest),
          bytes: largest.bytes,
          gzipBytes: gzipBytes(largest),
        }
      : null,
    mainJavaScript: main
      ? {
          path: relative(main),
          bytes: main.bytes,
          gzipBytes: gzipBytes(main),
        }
      : null,
    initialRequests: notMeasured("Requires a browser/network trace of the exact production build."),
  };
}

export function verifyLocalDist({ root }) {
  const dist = localDistTree(root);
  if (!dist.length) {
    throw new Error(
      "Local dist verification requested, but dist/ is missing. Build first or omit --verify-dist."
    );
  }
  const budget = JSON.parse(
    gitText(root, stage5BaselineProvenance.baseMainSha, "performance-budget.json")
  );
  const performance = productionDistPerformance(root, dist, budget);
  const failures = Object.entries(performance.metrics)
    .filter(([, metric]) => metric.result !== "PASS")
    .map(([name, metric]) => `${name}=${metric.actual}/${metric.limit}`);
  if (failures.length) {
    throw new Error(`Local dist exceeds the pinned budget: ${failures.join(", ")}`);
  }
  return {
    status: "PASS",
    classification: LOCAL_DIAGNOSTIC_CLASSIFICATION,
    acceptanceEvidence: false,
    artifact: performance.artifact,
    metrics: performance.metrics,
  };
}

function serviceWorkerBaseline(source) {
  const read = (name) => {
    const match = source.match(new RegExp(`const\\s+${name}\\s*=\\s*(?:\"([^\"]+)\"|(\\d+))`, "u"));
    return match ? match[1] ?? Number(match[2]) : NOT_MEASURED;
  };
  return {
    source: "public/sw.js",
    cacheVersion: read("CACHE_VERSION"),
    staticCacheLimit: read("STATIC_CACHE_LIMIT"),
    pageCacheLimit: read("PAGE_CACHE_LIMIT"),
    runtimeCacheContents: notMeasured("Requires a live browser service-worker inspection."),
  };
}

