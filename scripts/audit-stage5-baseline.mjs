export function buildStage5Baseline({ root }) {
  const { baseMainSha } = stage5BaselineProvenance;
  git(root, ["cat-file", "-e", `${baseMainSha}^{commit}`]);
  const styles = stage5BaselineProvenance.stylesheetPaths.map((file) => ({
    file,
    source: gitText(root, baseMainSha, file),
  }));
  const cssRules = styles.flatMap(({ file, source }) => parseCss(source, file));
  const categories = Object.fromEntries(
    Object.entries(inventoryRegistry).map(([category, definition]) => [
      category,
      inventoryFromRules(category, definition, cssRules),
    ])
  );
  const summary = { KEEP: 0, TUNE: 0, FIX: 0 };
  for (const entries of Object.values(categories)) {
    for (const entry of entries) summary[entry.decision] += 1;
  }

  const tree = gitTree(root, baseMainSha);
  const budget = JSON.parse(gitText(root, baseMainSha, "performance-budget.json"));
  const verifiedProductionEvidence = readVerifiedProductionEvidence(root, budget);
  const sourceArtifacts = {
    "public/assets": measuredFileSet(
      tree.filter((file) => file.path.startsWith("public/assets/"))
    ),
    "src/assets": measuredFileSet(
      tree.filter((file) => file.path.startsWith("src/assets/"))
    ),
    "book-cover assets": measuredFileSet(
      tree.filter((file) => /(?:^|\/)(?:book-covers|covers)\//u.test(file.path))
    ),
    "globe/map assets": measuredFileSet(
      tree.filter((file) => /(?:globe|world-map|antique-world|countries\.geojson)/iu.test(file.path))
    ),
  };
  const production = verifiedProductionEvidence.productionArtifact.performance;
  const performance = {
    budgetSource: "performance-budget.json",
    productionEvidence: {
      status: verifiedProductionEvidence.productionArtifact.status,
      classification: verifiedProductionEvidence.productionArtifact.classification,
      source: verifiedProductionEvidence.productionArtifact.source,
      acceptanceEvidence: true,
    },
    verifiedBuildGate: exactProductionBuildGate(verifiedProductionEvidence),
    production,
    localDistDiagnostic: {
      status: "NOT RUN",
      classification: LOCAL_DIAGNOSTIC_CLASSIFICATION,
      acceptanceEvidence: false,
      command: "npm run stage5:baseline:verify-dist",
    },
    sourceArtifacts,
    sourceCss: measuredFileSet(
      tree.filter((file) => stage5BaselineProvenance.stylesheetPaths.includes(file.path))
    ),
    serviceWorker: serviceWorkerBaseline(gitText(root, baseMainSha, "public/sw.js")),
  };
  const appSource = gitText(root, baseMainSha, "src/App.tsx");
  const currentOrder = currentHomepageOrder(appSource);
  const landmarks = sectionLandmarkRegistry.map(([landmark, selector]) => {
    const declaredRules = cssRules.filter((rule) => rule.selector === selector);
    if (!declaredRules.length) {
      throw new Error(`Section landmark selector missing from pinned CSS: ${selector}`);
    }
    return { landmark, selector, declaredRules };
  });
  const reviewedSources = sourceReview(root, baseMainSha);
  const baseline = {
    provenance: {
      ...stage5BaselineProvenance,
      evidenceSource:
        "git object database at BASE_MAIN_SHA + exact official GitHub Pages artifact 9517505146 from workflow run 32719497676",
    },
    ownerLocks,
    governanceFingerprints: governanceFingerprintRegistry.map(
      ({ id, paths, classTokens, expected }) => ({
        id,
        paths,
        ...(classTokens ? { classTokens } : {}),
        expected,
      })
    ),
    runtimeObservedFindings,
    sourceReview: reviewedSources,
    performance,
    sectionLandmarks: {
      entries: landmarks.map(({ landmark, selector, declaredRules }) => ({
        landmark,
        selector,
        sourceRuleCount: declaredRules.length,
        computedCoordinates: NOT_MEASURED,
      })),
      currentHomepageOrder: currentOrder.map((item) => item.label),
      targetStage5cOrder,
    },
    visualEvidence: {
      screenshots: "NOT CAPTURED",
      computedStyles: {
        default: NOT_MEASURED,
        measuredFindings: runtimeObservedFindings.map((finding) => finding.id),
      },
      reason: "No reliable browser screenshot capture was available for the production build.",
      viewports: visualViewportRegistry,
      closeups: visualCloseupRegistry,
      states: visualStateRegistry,
    },
    inventories: { summary },
  };
  const inventories = {
    provenance: baseline.provenance,
    computedValues: {
      default: { status: NOT_MEASURED, reason: COMPUTED_REASON },
      measuredFindings: runtimeObservedFindings,
    },
    summary,
    categories,
  };

  const files = {
    "reports/stage5-baseline/README.md": renderBaselineReadme(baseline),
    "reports/stage5-baseline/baseline.json": `${JSON.stringify(baseline, null, 2)}\n`,
    "reports/stage5-baseline/performance.md": renderPerformance(performance),
    "reports/stage5-baseline/performance.json": `${JSON.stringify(performance, null, 2)}\n`,
    "reports/stage5-baseline/section-landmarks.md": renderLandmarks(
      landmarks,
      currentOrder
    ),
    "reports/stage5-baseline/source-review.md": renderSourceReview(reviewedSources),
    "reports/stage5-baseline/visual-capture-matrix.md": renderVisualMatrix(),
    "reports/stage5-inventories/README.md": renderInventoryReadme(inventories),
    "reports/stage5-inventories/inventories.json": `${JSON.stringify(inventories, null, 2)}\n`,
  };
  for (const [category, definition] of Object.entries(inventoryRegistry)) {
    files[`reports/stage5-inventories/${category}.md`] = renderInventory(
      category,
      definition,
      categories[category]
    );
  }
  return { baseline, inventories, files };
}

async function writeGeneratedFiles(root, files) {
  for (const [relativePath, content] of Object.entries(files)) {
    const target = path.join(root, relativePath);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content, "utf8");
  }
}

async function checkGeneratedFiles(root, files) {
  const drift = [];
  for (const [relativePath, expected] of Object.entries(files)) {
    try {
      const actual = await readFile(path.join(root, relativePath), "utf8");
      if (actual !== expected) drift.push(relativePath);
    } catch (error) {
      if (error?.code === "ENOENT") drift.push(relativePath);
      else throw error;
    }
  }
  if (drift.length) {
    throw new Error(
      `Stage 5A baseline drift: ${drift.join(", ")}. Run npm run stage5:baseline:write.`
    );
  }
}

async function main() {
  const root = process.cwd();
  const write = process.argv.includes("--write");
  const verifyDist = process.argv.includes("--verify-dist");
  const check = process.argv.includes("--check") || !write;
  const generated = buildStage5Baseline({ root });
  if (write) await writeGeneratedFiles(root, generated.files);
  if (check) await checkGeneratedFiles(root, generated.files);
  console.log(
    `${write ? "WROTE" : "PASS"} Stage 5A baseline: ${Object.keys(generated.files).length} files, ` +
      `${generated.inventories.summary.KEEP} KEEP / ${generated.inventories.summary.TUNE} TUNE / ${generated.inventories.summary.FIX} FIX.`
  );
  if (verifyDist) {
    const diagnostic = verifyLocalDist({ root });
    console.log(
      `PASS local dist diagnostic: ${diagnostic.artifact.files} files / ${diagnostic.artifact.bytes} bytes; ` +
        `${diagnostic.classification}; acceptanceEvidence=false.`
    );
  }
}

