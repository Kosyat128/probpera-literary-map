import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  normalizeArticlePublicMetadata,
  normalizePublicMetadataText,
} from "./lib/article-route-policy.mjs";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicCms = path.join(projectRoot, "public", "cms");
const cmsArticles = path.join(publicCms, "articles");
const generatedCatalog = path.join(projectRoot, "src", "data", "articles", "cms.generated.ts");
const write = process.argv.includes("--write");

function asGeneratedModule(value) {
  return `// Generated by scripts/export-published-content.mjs. Do not edit by hand.\n// Public article metadata exported through read-only RLS policies.\nexport const cmsArticleCatalog = ${JSON.stringify(value, null, 2)} as const;\n`;
}

async function readJson(file) {
  return JSON.parse(await fs.readFile(file, "utf8"));
}

function normalizeDocument(document) {
  const metadata = normalizeArticlePublicMetadata(document);
  return {
    ...document,
    ...metadata,
    translations: document.translations?.en
      ? {
          ...document.translations,
          en: {
            ...document.translations.en,
            ...normalizeArticlePublicMetadata(document.translations.en),
          },
        }
      : document.translations,
  };
}

const publishedContentPath = path.join(publicCms, "published-content.json");
const publishedArticlesPath = path.join(publicCms, "published-articles.json");
const publishedContent = await readJson(publishedContentPath);
const publishedArticles = await readJson(publishedArticlesPath);
const articles = (publishedContent.articles || []).map(normalizeArticlePublicMetadata);
const changed = [];

for (const article of articles) {
  const documentPath = path.join(cmsArticles, `${article.id}.json`);
  const document = await readJson(documentPath);
  const normalized = normalizeDocument(document);
  const current = JSON.stringify(document, null, 2);
  const next = JSON.stringify(normalized, null, 2);
  if (current !== next) {
    changed.push(article.id);
    if (write) await fs.writeFile(documentPath, `${next}\n`, "utf8");
  }
}

const normalizedPublishedContent = { ...publishedContent, articles };
const normalizedPublishedArticles = {
  ...publishedArticles,
  articles: (publishedArticles.articles || []).map(normalizeArticlePublicMetadata),
};
const outputs = [
  [publishedContentPath, `${JSON.stringify(normalizedPublishedContent, null, 2)}\n`],
  [publishedArticlesPath, `${JSON.stringify(normalizedPublishedArticles, null, 2)}\n`],
  [generatedCatalog, asGeneratedModule(articles)],
];
for (const [file, next] of outputs) {
  const current = await fs.readFile(file, "utf8");
  if (current !== next) {
    changed.push(path.relative(projectRoot, file));
    if (write) await fs.writeFile(file, next, "utf8");
  }
}

if (changed.length && !write) {
  throw new Error(
    `CMS metadata requires whitespace normalization (${changed.length} artifacts). Run npm run content:metadata:fix.`
  );
}
console.log(
  write
    ? `Normalized CMS metadata: ${changed.length} artifact(s).`
    : `CMS metadata ready: ${articles.length} article(s), 0 mismatches.`
);
