import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';

const base = process.env.LITERARY_NEWS_PREVIEW_URL || 'http://127.0.0.1:5188/probpera-literary-map/';
const output = fileURLToPath(new URL('../.tmp/literary-news-evidence/', import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' });
const context = await browser.newContext({ viewport: { width: 1365, height: 1050 }, timezoneId: 'Europe/Moscow' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const results = [];
try {
  await page.goto(`${base}news-preview.html`, { waitUntil: 'networkidle' });
  const panel = page.locator('#literary-news');
  await panel.locator('article').first().waitFor();
  const feed = await page.request.get(new URL('/__literary-news/feed?timeZone=Europe%2FMoscow', base).href).then(response => response.json());
  assert.ok(feed.items.length >= 25, 'The reviewed digest covers more than the original five examples');
  assert.ok(feed.sources.length >= 20, 'The source registry has worldwide coverage');
  const firstStory = feed.items[0];
  assert.equal(await panel.locator('article').count(), 3);
  assert.equal(await panel.getByRole('button', { name: 'RU', exact: true }).count(), 0);
  assert.ok((await panel.innerText()).includes(firstStory.title.ru));
  await page.screenshot({ path: `${output}/desktop-ru.png`, fullPage: true });
  results.push('RU cards and compact panel loaded');

  await page.locator('header .interface-language-control button').filter({ hasText: 'EN' }).click();
  assert.match(await panel.innerText(), /The literary briefing/);
  assert.ok((await panel.innerText()).includes(firstStory.title.en));
  assert.doesNotMatch(await panel.locator('h3,.literary-news__summary,.literary-news__category').allInnerTexts().then((v) => v.join(' ')), /[А-Яа-яЁё]/);
  results.push('Existing header language switch updates titles, summaries and labels');
  await page.screenshot({ path: `${output}/desktop-en.png`, fullPage: true });

  await panel.getByRole('button', { name: 'Today', exact: true }).click();
  const today = await page.evaluate(() => new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Moscow', year: 'numeric', month: '2-digit', day: '2-digit' }).format(Date.now()));
  const todayItems = feed.items.filter(item => item.eventDate === today);
  assert.equal(await panel.locator('article').count(), Math.min(3, todayItems.length));
  if (!todayItems.length) assert.match(await panel.innerText(), /No confirmed events for today yet/);
  await panel.getByRole('button', { name: 'All', exact: true }).click();
  await panel.getByRole('button', { name: /All events/ }).click();
  assert.equal(await panel.locator('article').count(), feed.items.length);
  assert.equal(await panel.locator('.literary-news__content').evaluate(node => node.clientHeight <= 582 && node.scrollHeight > node.clientHeight), true, 'Expanded digest scrolls inside the panel');
  results.push('Today never treats old examples or source fetches as new events; expansion works');

  await page.setViewportSize({ width: 390, height: 844 });
  await panel.getByRole('button', { name: 'Show less' }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.screenshot({ path: `${output}/mobile-en.png`, fullPage: true });
  results.push('390px mobile layout has no horizontal overflow');

  await page.route('**/__literary-news/feed*', (route) => route.fulfill({ status: 503, body: '{}' }));
  await panel.getByRole('button', { name: 'Refresh news' }).click();
  await panel.locator('.literary-news__feed-details > summary').click();
  await panel.getByText('Updates are temporarily unavailable. Showing the last received events.').waitFor();
  assert.equal(await panel.locator('article').count(), 3);
  await page.unroute('**/__literary-news/feed*');
  results.push('Failure retains last feed and shows its status inside Sources and review');

  await page.setViewportSize({ width: 1585, height: 1050 });
  await page.goto(`${base}?literary-news=1#book-day`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.locator('#literary-news article').first().waitFor({ timeout: 60000 });
  assert.equal(await page.locator('#literary-news h2').innerText(), 'The literary briefing');
  assert.equal(await page.locator('#book-day .book-month-supporting #literary-news').count(), 1);
  const sidebar = page.locator('#literary-news');
  assert.equal(await sidebar.locator('.literary-news__limited').count(), 0);
  const book = page.locator('#book-day .book-of-day');
  await book.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => {
    const title = document.querySelector('#book-day .book-of-day h4')?.textContent || '';
    return title && !title.includes('Opening') && !title.includes('Открываем');
  });
  await page.evaluate(() => document.fonts.ready);
  const bookRect = await book.boundingBox();
  const newsRect = await sidebar.boundingBox();
  assert.ok(newsRect.x >= bookRect.x + bookRect.width, 'News stays to the right of the book');
  assert.ok(newsRect.height < 780, 'Default sidebar remains compact with region controls');
  const factRect = await page.locator('#book-day .book-fact-card').boundingBox();
  assert.ok(Math.abs((bookRect.y + bookRect.height) - (factRect.y + factRect.height)) <= 1, 'Fact and book share the bottom edge');
  await page.locator('#book-day').screenshot({ path: `${output}/book-month-world-en.png` });
  await sidebar.locator('.literary-news__story-details summary').first().click();
  assert.equal(await sidebar.locator('.literary-news__summary').first().isVisible(), true);
  assert.match(await sidebar.locator('.literary-news__story-details').first().innerText(), /Reviewed/);
  await sidebar.locator('.literary-news__story-details summary').first().click();
  const firstHeadline = sidebar.locator('h3 button').first();
  await firstHeadline.focus();
  await page.keyboard.press('Enter');
  assert.equal(await firstHeadline.getAttribute('aria-expanded'), 'true');
  assert.equal(await sidebar.locator('.literary-news__summary').first().isVisible(), true);
  await firstHeadline.click();
  await sidebar.getByLabel('News topic').selectOption('adaptations');
  assert.equal(await sidebar.locator('article').count(), Math.min(3, feed.items.filter(item => item.category === 'adaptations').length));
  const savedStory = sidebar.locator('article[data-news-id="love-hypothesis-2026-release-announcement"]');
  assert.match(await savedStory.locator('h3').innerText(), /Love Hypothesis/);
  await savedStory.locator('.literary-news__bookmark').click();
  assert.equal(await savedStory.locator('.literary-news__bookmark').getAttribute('aria-pressed'), 'true');
  await sidebar.locator('.literary-news__saved-filter').click();
  assert.equal(await sidebar.locator('article').count(), 1);
  await sidebar.getByLabel('News topic').selectOption('awards');
  assert.equal(await sidebar.locator('article').count(), 0);
  assert.match(await sidebar.innerText(), /No saved stories match these filters/);
  await sidebar.getByRole('button', { name: 'Show all news', exact: true }).click();
  assert.equal(await sidebar.locator('article').count(), 3);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await sidebar.locator('article').first().waitFor({ timeout: 60000 });
  await sidebar.locator('.literary-news__saved-filter').click();
  assert.equal(await sidebar.locator('article').count(), 1);
  assert.match(await sidebar.locator('h3').innerText(), /Love Hypothesis/);
  await page.locator('.interface-language-control button').filter({ hasText: 'RU' }).first().click();
  assert.match(await sidebar.locator('h3').innerText(), /Гипотезы любви/);
  assert.equal(await sidebar.locator('.literary-news__saved-filter').getAttribute('aria-pressed'), 'true');
  await sidebar.locator('.literary-news__bookmark').click();
  assert.equal(await sidebar.locator('article').count(), 0);
  assert.match(await sidebar.innerText(), /Вы ещё не сохранили новости/);
  await sidebar.locator('.literary-news__saved-filter').click();
  results.push('Topic and Saved filters combine correctly; bookmarks persist across reload and language changes; headline opens via Enter');
  await page.locator('.interface-language-control button').filter({ hasText: 'RU' }).first().click();
  assert.ok((await sidebar.innerText()).includes(firstStory.title.ru));
  await book.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => {
    const title = document.querySelector('#book-day .book-of-day h4')?.textContent || '';
    return title && !title.includes('Opening') && !title.includes('Открываем');
  }, { timeout: 60000 });
  await page.evaluate(() => document.fonts.ready);
  const alignedRu = await page.locator('#book-day').evaluate((section) => {
    const book = section.querySelector('.book-of-day').getBoundingClientRect();
    const fact = section.querySelector('.book-fact-card').getBoundingClientRect();
    return Math.abs(book.bottom - fact.bottom) <= 1;
  });
  assert.equal(alignedRu, true, 'The bottom edge stays aligned after switching to Russian');
  await page.locator('#book-day').screenshot({ path: `${output}/book-month-world-ru.png` });
  await page.locator('.news-editorial-context summary').click();
  const alignedExpanded = await page.locator('#book-day').evaluate((section) => {
    const book = section.querySelector('.book-of-day').getBoundingClientRect();
    const fact = section.querySelector('.book-fact-card').getBoundingClientRect();
    return Math.abs(book.bottom - fact.bottom) <= 1;
  });
  assert.equal(alignedExpanded, true, 'Opening editorial policy keeps the cards aligned');
  assert.equal(await page.locator('.news-editorial-context .editorial-standard').isVisible(), true);
  await page.locator('.news-editorial-context summary').click();
  results.push('Sidebar fits beside book of the month; RU/EN, full story details and editorial policy remain accessible');
  results.push('Book and fact bottom edges match within one pixel in RU and EN');
  await page.setViewportSize({ width: 390, height: 844 });
  await sidebar.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await sidebar.screenshot({ path: `${output}/world-sidebar-mobile-ru.png` });
  results.push('Homepage sidebar stacks on mobile without horizontal overflow');
  assert.deepEqual(errors, []);
  await writeFile(`${output}/checks.json`, JSON.stringify({ passed: results, pageErrors: errors }, null, 2));
  console.log(JSON.stringify({ passed: results, evidence: output }, null, 2));
} finally {
  await browser.close();
}
