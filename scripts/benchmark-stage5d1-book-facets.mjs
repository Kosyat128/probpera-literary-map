import { mkdtemp, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

import { build } from "esbuild";

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  ".."
);
const temporaryDirectory = await mkdtemp(
  path.join(os.tmpdir(), "probpera-stage5d1-facets-")
);
const bundlePath = path.join(temporaryDirectory, "benchmark.mjs");
const archiveSourcePath = path.join(projectRoot, "scripts", "archive-source.ts");
const queuePath = path.join(projectRoot, "src", "data", "bookArchiveQueue.ts");
const facetsPath = path.join(
  projectRoot,
  "src",
  "books",
  "bookArchiveFacets.ts"
);
const mentionIndexPath = path.join(
  projectRoot,
  "public",
  "articles",
  "book-mentions.json"
);

const entrySource = [
  'import { readFileSync } from "node:fs";',
  'import os from "node:os";',
  'import { performance } from "node:perf_hooks";',
  "import { archiveBooks } from " + JSON.stringify(archiveSourcePath) + ";",
  "import { classifyBookArchiveQueue } from " + JSON.stringify(queuePath) + ";",
  "import {",
  "  applyBookArchiveQuickPreset,",
  "  buildBookArchiveFacetIndex,",
  "  filterBookArchiveFacetIndex,",
  "  normalizeBookArchiveFilterState,",
  "} from " + JSON.stringify(facetsPath) + ";",
  "",
  "const TARGET_SIZE = 10_000;",
  "const mentionIndex = JSON.parse(",
  "  readFileSync(" + JSON.stringify(mentionIndexPath) + ', "utf8")',
  ");",
  "const corpus = archiveBooks.slice(0, TARGET_SIZE);",
  "for (let index = corpus.length; index < TARGET_SIZE; index += 1) {",
  "  const source = archiveBooks[index % archiveBooks.length];",
  "  const suffix = '-stage5d1-benchmark-' + index;",
  "  corpus.push({",
  "    ...source,",
  "    id: source.id + suffix,",
  "    title: source.title + ' ' + index,",
  "    translations: source.translations",
  "      ? Object.fromEntries(",
  "          Object.entries(source.translations).map(([locale, translation]) => [",
  "            locale,",
  "            translation",
  "              ? { ...translation, title: translation.title + ' ' + index }",
  "              : translation,",
  "          ])",
  "        )",
  "      : source.translations,",
  "  });",
  "}",
  "const queue = classifyBookArchiveQueue(corpus);",
  "const buildIndex = () =>",
  "  buildBookArchiveFacetIndex({",
  "    items: queue.all,",
  "    locale: 'ru',",
  "    mentionIndex,",
  "  });",
  "const percentile = (samples, value) => {",
  "  const sorted = [...samples].sort((left, right) => left - right);",
  "  return sorted[Math.max(0, Math.ceil(sorted.length * value) - 1)] || 0;",
  "};",
  "const round = (value) => Math.round(value * 1000) / 1000;",
  "",
  "for (let warmup = 0; warmup < 3; warmup += 1) buildIndex();",
  "const buildSamples = [];",
  "let index;",
  "for (let sample = 0; sample < 20; sample += 1) {",
  "  const startedAt = performance.now();",
  "  index = buildIndex();",
  "  buildSamples.push(performance.now() - startedAt);",
  "}",
  "const savedBookKeys = new Set(",
  "  index.documents.filter((_, position) => position % 11 === 0).map(({ key }) => key)",
  ");",
  "const firstCountry = index.documents[0]?.countryId || '';",
  "const firstAuthor = index.documents[0]?.authorKey || null;",
  "const exactTitle = index.documents.find(({ title }) => title.length > 4)?.title || '';",
  "const initial = normalizeBookArchiveFilterState();",
  "const workloads = [",
  "  initial,",
  "  applyBookArchiveQuickPreset(initial, 'verified'),",
  "  applyBookArchiveQuickPreset(initial, 'classic'),",
  "  applyBookArchiveQuickPreset(initial, 'modern'),",
  "  applyBookArchiveQuickPreset(initial, 'with-cover'),",
  "  normalizeBookArchiveFilterState({ countryIds: [firstCountry] }),",
  "  normalizeBookArchiveFilterState({ authorKey: firstAuthor }),",
  "  normalizeBookArchiveFilterState({ query: exactTitle }),",
  "  normalizeBookArchiveFilterState({ query: 'роман' }),",
  "  normalizeBookArchiveFilterState({",
  "    countryIds: [firstCountry],",
  "    editorialStatuses: ['verified'],",
  "    coverModes: ['uploaded', 'editorial'],",
  "  }),",
  "  applyBookArchiveQuickPreset(initial, 'saved'),",
  "];",
  "const workloadNames = [",
  "  'all', 'verified', 'classic', 'modern', 'with-cover', 'country',",
  "  'author', 'exact-title', 'genre-query', 'combined', 'saved',",
  "];",
  "const runWorkload = (state) =>",
  "  filterBookArchiveFacetIndex(index, state, { savedBookKeys });",
  "for (let warmup = 0; warmup < 5; warmup += 1) workloads.forEach(runWorkload);",
  "const querySamples = [];",
  "const querySamplesByWorkload = workloads.map(() => []);",
  "for (let sample = 0; sample < 30; sample += 1) {",
  "  for (let workloadIndex = 0; workloadIndex < workloads.length; workloadIndex += 1) {",
  "    const workload = workloads[workloadIndex];",
  "    const startedAt = performance.now();",
  "    runWorkload(workload);",
  "    const duration = performance.now() - startedAt;",
  "    querySamples.push(duration);",
  "    querySamplesByWorkload[workloadIndex].push(duration);",
  "  }",
  "}",
  "const queryP95 = percentile(querySamples, 0.95);",
  "console.log(JSON.stringify({",
  "  corpusSize: corpus.length,",
  "  workloadCount: workloads.length,",
  "  buildSamples: buildSamples.length,",
  "  querySamples: querySamples.length,",
  "  queryP95ByWorkloadMs: Object.fromEntries(",
  "    workloadNames.map((name, index) => [",
  "      name,",
  "      round(percentile(querySamplesByWorkload[index], 0.95)),",
  "    ])",
  "  ),",
  "  indexBuildP50Ms: round(percentile(buildSamples, 0.5)),",
  "  indexBuildP95Ms: round(percentile(buildSamples, 0.95)),",
  "  queryP50Ms: round(percentile(querySamples, 0.5)),",
  "  queryP95Ms: round(queryP95),",
  "  desktopQueryTarget: queryP95 < 50 ? 'PASS' : 'FAIL',",
  "  balancedMobileQueryTarget: 'NOT MEASURED',",
  "  audienceFacetStatus: index.diagnostics.audienceFacetStatus,",
  "  relationFacetStatus: index.diagnostics.relationFacetStatus,",
  "  runtime: {",
  "    node: process.version,",
  "    platform: process.platform,",
  "    architecture: process.arch,",
  "    cpu: os.cpus()[0]?.model || 'unknown',",
  "  },",
  "}, null, 2));",
].join("\n");

try {
  await build({
    absWorkingDir: projectRoot,
    stdin: {
      contents: entrySource,
      resolveDir: projectRoot,
      sourcefile: "stage5d1-book-facets-benchmark.ts",
      loader: "ts",
    },
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    outfile: bundlePath,
    logLevel: "silent",
  });
  await import(pathToFileURL(bundlePath).href);
} finally {
  await rm(temporaryDirectory, { recursive: true, force: true });
}
