import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { load } from "cheerio";

import { drakePublication } from "./fixtures/drake-publication.mjs";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicCmsDirectory = path.join(projectRoot, "public", "cms");
const documentId = `cms-${drakePublication.id}`;
const publicPath = `/stati/raznoe/${drakePublication.slug}/`;
const canonicalUrl = `https://probpera.ru${publicPath}`;
const normalizedText = (value = "") => String(value).replace(/\s+/gu, " ").trim();

const $ = load(`<main id="drake-publication">${drakePublication.content_html}</main>`, {
  decodeEntities: false,
});
const plainText = normalizedText($("#drake-publication").text());
const headings = $("#drake-publication h1, #drake-publication h2, #drake-publication h3")
  .toArray()
  .map((heading) => ({
    id: $(heading).attr("id") || "",
    level: Number(heading.tagName.slice(1)),
    text: normalizedText($(heading).text()),
  }));
const wordCount = plainText ? plainText.split(/\s+/gu).length : 0;

const metadata = {
  id: documentId,
  source: "cms",
  legacyId: drakePublication.legacy_id,
  legacyPath: drakePublication.legacy_path,
  url: canonicalUrl,
  canonicalUrl,
  slug: drakePublication.slug,
  title: drakePublication.title,
  description: drakePublication.excerpt,
  imageUrl: drakePublication.cover_external_url,
  imageAlt: drakePublication.cover_alt,
  sectionId: "miscellaneous",
  sectionLabel: "Разное",
  publishedLabel: "Опубликовано: 06 февраля 2026",
  publishedAt: drakePublication.published_at,
  readingMinutes: Math.max(1, Math.ceil(wordCount / 180)),
  wordCount,
  headingCount: headings.length,
  documentPath: `cms/articles/${documentId}.json`,
  featured: drakePublication.featured,
  showOnHomepage: drakePublication.show_on_homepage,
  pinned: drakePublication.pinned,
  seoTitle: drakePublication.seo_title,
  seoDescription: drakePublication.seo_description,
  seoKeywords: drakePublication.seo_keywords,
  ogTitle: drakePublication.og_title,
  ogDescription: drakePublication.og_description,
  ogImageUrl: drakePublication.cover_external_url,
  allowIndexing: drakePublication.allow_indexing,
};

const document = {
  ...metadata,
  contentHtml: drakePublication.content_html,
  plainText,
  headings,
  sources: drakePublication.sources,
  bibliography: drakePublication.bibliography,
};

function withDrake(articles = []) {
  return [...articles.filter((article) => article.id !== documentId), metadata].sort(
    (first, second) =>
      Number(Boolean(second.pinned)) - Number(Boolean(first.pinned)) ||
      Number(Boolean(second.featured)) - Number(Boolean(first.featured)) ||
      Date.parse(second.publishedAt || "") - Date.parse(first.publishedAt || "")
  );
}

const publishedContentPath = path.join(publicCmsDirectory, "published-content.json");
const publishedArticlesPath = path.join(publicCmsDirectory, "published-articles.json");
const generatedCatalogPath = path.join(
  projectRoot,
  "src",
  "data",
  "articles",
  "cms.generated.ts"
);
const publishedContent = JSON.parse(await fs.readFile(publishedContentPath, "utf8"));
const publishedArticles = JSON.parse(await fs.readFile(publishedArticlesPath, "utf8"));
const articles = withDrake(publishedContent.articles);

await fs.writeFile(
  path.join(publicCmsDirectory, "articles", `${documentId}.json`),
  `${JSON.stringify(document, null, 2)}\n`,
  "utf8"
);
await fs.writeFile(
  publishedContentPath,
  `${JSON.stringify({ ...publishedContent, articles }, null, 2)}\n`,
  "utf8"
);
await fs.writeFile(
  publishedArticlesPath,
  `${JSON.stringify(
    { ...publishedArticles, articles: withDrake(publishedArticles.articles) },
    null,
    2
  )}\n`,
  "utf8"
);
await fs.writeFile(
  generatedCatalogPath,
  `// Generated by scripts/export-published-content.mjs. Do not edit by hand.\n// Public article metadata exported through read-only RLS policies.\nexport const cmsArticleCatalog = ${JSON.stringify(
    articles,
    null,
    2
  )} as const;\n`,
  "utf8"
);

console.log(
  `Drake snapshot ready: ${articles.length} CMS articles, ${wordCount} words, ${headings.length} headings.`
);
